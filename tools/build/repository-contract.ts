import { RepositoryPackageSchema, REPOSITORY_VERSIONS } from "../../packages/protocol/src/repository.ts";
import { ServiceManifestSchema, APIAuthSchema } from "../../packages/protocol/src/manifest.ts";
import { IOSCatalogManifestSchema, MCPCatalogManifestSchema } from "../../packages/protocol/src/catalog.ts";
import { checkGenerated, writeGenerated, runCheck } from "../lib.ts";

export function artifacts(): Record<string, string> {
  const schema = {
    $schema: "http://json-schema.org/draft-07/schema#",
    $id: `urn:openox:repository:${REPOSITORY_VERSIONS.at(-1)}`,
    title: "OpenOx Host-Repository content contract",
    $ref: "#/definitions/RepositoryPackage",
    definitions: {
      RepositoryPackage: RepositoryPackageSchema,
      ServiceManifest: ServiceManifestSchema,
      APIAuth: APIAuthSchema,
      IOSCatalogManifest: IOSCatalogManifestSchema,
      MCPCatalogManifest: MCPCatalogManifestSchema,
    },
  };
  const swift = `// Generated by bun tools/build/repository-contract.ts --write. Do not edit.\n\nnonisolated extension HostProtocols {\n    static let repository = [${REPOSITORY_VERSIONS.join(", ")}]\n}\n`;
  return {
    "packages/protocol/repository.schema.json": JSON.stringify(schema, null, 2) + "\n",
    "apps/ios/Ox/Host/HostRepositoryContract.swift": swift,
  };
}

export async function check(): Promise<string> {
  await checkGenerated(artifacts(), "build:repository-schema");
  return `Host-Repository contract: versions ${REPOSITORY_VERSIONS.join(", ")}, portable schemas and iOS version synchronized`;
}

if (import.meta.main) {
  if (process.argv.includes("--write")) await writeGenerated(artifacts());
  else await runCheck(check);
}
